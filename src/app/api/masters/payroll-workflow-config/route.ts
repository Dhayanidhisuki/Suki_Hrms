/**
 * GET  /api/masters/payroll-workflow-config — this company's workflow config (or defaults).
 * PUT  /api/masters/payroll-workflow-config — upsert this company's workflow config.
 */

import { NextRequest, NextResponse } from 'next/server';
import { prisma } from '@/lib/prisma';
import { checkMasterPermission } from '@/lib/rbac-masters';
import { getCompanyId } from '@/lib/companyScope';
import { payrollWorkflowConfigSchema } from '@/lib/validations/master';

const DEFAULTS = {
  enableValidatedStage: false,
  enableSubmittedStage: false,
  enablePostedStage: false,
  approvalStages: 'HR',
  cutoffDayOfMonth: null,
  allowReopenAfterLock: true,
  reopenRequiresReason: true,
};

export async function GET(request: NextRequest) {
  const permErr = await checkMasterPermission(request);
  if (permErr) return permErr;
  const scope = getCompanyId(request);
  if ('error' in scope) return scope.error;

  const record = await prisma.payrollWorkflowConfig.findUnique({ where: { companyId: scope.companyId } });
  return NextResponse.json(record ?? DEFAULTS);
}

export async function PUT(request: NextRequest) {
  const permErr = await checkMasterPermission(request);
  if (permErr) return permErr;
  const scope = getCompanyId(request);
  if ('error' in scope) return scope.error;

  const parsed = payrollWorkflowConfigSchema.safeParse(await request.json().catch(() => null));
  if (!parsed.success) {
    return NextResponse.json({ error: 'Validation failed', details: parsed.error.flatten() }, { status: 400 });
  }

  const record = await prisma.payrollWorkflowConfig.upsert({
    where: { companyId: scope.companyId },
    create: { ...parsed.data, companyId: scope.companyId },
    update: parsed.data,
  });

  return NextResponse.json(record);
}
