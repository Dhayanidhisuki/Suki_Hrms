import { PrismaClient } from '@prisma/client';
const p = new PrismaClient();
const print = (t, rows) => {
  console.log('\n' + '='.repeat(72) + '\n' + t + '\n' + '='.repeat(72));
  console.log(!rows?.length ? '(no rows)' : JSON.stringify(rows, (_, v) => typeof v === 'bigint' ? v.toString() : v, 2));
};
const q = (sql) => p.$queryRawUnsafe(sql);
try {
  print('GAP 1 follow — TOOLS_MAPPING count + columns', await q(`
    SELECT (SELECT COUNT(*) FROM TOOLS_MAPPING) AS RowCount
  `));
  print('GAP 1 follow — TOOLS_MAPPING columns', await q(`
    SELECT COLUMN_NAME, DATA_TYPE, CHARACTER_MAXIMUM_LENGTH
    FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_NAME='TOOLS_MAPPING' ORDER BY ORDINAL_POSITION
  `));
  print('GAP 1 follow — any SUPPLIER/VENDOR tool link tables', await q(`
    SELECT TABLE_NAME FROM INFORMATION_SCHEMA.TABLES
    WHERE TABLE_NAME LIKE '%SUPPLIER%TOOL%' OR TABLE_NAME LIKE '%TOOL%SUPPLIER%'
       OR TABLE_NAME LIKE '%VENDOR%TOOL%' OR TABLE_NAME LIKE '%TOOL%VENDOR%'
       OR TABLE_NAME LIKE '%TOOLS_PRICE%'
    ORDER BY TABLE_NAME
  `));

  print('GAP 2 follow — MATERIAL_REQUISITION_MASTER columns', await q(`
    SELECT COLUMN_NAME FROM INFORMATION_SCHEMA.COLUMNS
    WHERE TABLE_NAME='MATERIAL_REQUISITION_MASTER' ORDER BY ORDINAL_POSITION
  `));
  print('GAP 2 follow — MATERIAL_INDENT_MASTER columns', await q(`
    SELECT COLUMN_NAME FROM INFORMATION_SCHEMA.COLUMNS
    WHERE TABLE_NAME='MATERIAL_INDENT_MASTER' ORDER BY ORDINAL_POSITION
  `));
  print('GAP 2 follow — sample MATERIAL_REQUISITION_MASTER', await q(`SELECT TOP 3 * FROM MATERIAL_REQUISITION_MASTER ORDER BY 1 DESC`));
  print('GAP 2 follow — sample MATERIAL_INDENT_MASTER', await q(`SELECT TOP 3 * FROM MATERIAL_INDENT_MASTER ORDER BY 1 DESC`));

  print('GAP 4 follow — PURCHASE_ORDER columns (top 30)', await q(`
    SELECT TOP 30 COLUMN_NAME FROM INFORMATION_SCHEMA.COLUMNS
    WHERE TABLE_NAME='PURCHASE_ORDER' ORDER BY ORDINAL_POSITION
  `));
  print('GAP 4 follow — PURCHASE_ORDER sample linked to tools POs', await q(`
    SELECT TOP 5 PO_ORDER_NO FROM TOOLS_PO_RECEIVE WHERE PO_ORDER_NO IS NOT NULL ORDER BY GIR_NO DESC
  `));
  print('GAP 4 follow — does PURCHASE_ORDER hold those PO numbers?', await q(`
    SELECT TOP 5 * FROM PURCHASE_ORDER
    WHERE PO_ORDER_NO IN (SELECT TOP 5 PO_ORDER_NO FROM TOOLS_PO_RECEIVE WHERE PO_ORDER_NO IS NOT NULL ORDER BY GIR_NO DESC)
  `));
  print('GAP 4 follow — COMMON_PURCHASE_ORDER sample cols', await q(`
    SELECT COLUMN_NAME FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_NAME='COMMON_PURCHASE_ORDER' ORDER BY ORDINAL_POSITION
  `));
  print('GAP 4 follow — COMMON_PURCHASE_ORDER TOP 3', await q(`SELECT TOP 3 * FROM COMMON_PURCHASE_ORDER`));

  print('GAP 5 follow — COMPANY_DETAILS TOP 3', await q(`SELECT TOP 3 * FROM COMPANY_DETAILS`));
  print('GAP 6 follow — MULTI_LEVEL_APPROVAL_MASTER TOP 3', await q(`SELECT TOP 3 * FROM MULTI_LEVEL_APPROVAL_MASTER`));
  print('GAP 6 follow — PURCHASE_APPROVAL TOP 3', await q(`SELECT TOP 3 * FROM PURCHASE_APPROVAL`));
  print('GAP 8 follow — LOG_DETAILS columns + sample', await q(`
    SELECT COLUMN_NAME FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_NAME='LOG_DETAILS' ORDER BY ORDINAL_POSITION
  `));
  print('GAP 8 follow — LOG_DETAILS TOP 5', await q(`SELECT TOP 5 * FROM LOG_DETAILS ORDER BY 1 DESC`));
  print('GAP 8 follow — LOGIN_TRACKING TOP 3', await q(`SELECT TOP 3 * FROM LOGIN_TRACKING ORDER BY 1 DESC`));
} catch (e) {
  console.error('FATAL', e.message);
} finally {
  await p.$disconnect();
}
